"""Generate fixed v1-kernel fixtures with Python reference scores.

Writes ``ml/tests/kernel_v1_fixtures.json`` (generated — do not
hand-edit): the SAME 60 positions as ``ml/tests/kernel_fixtures.json``
(read from that file, so the two fixture sets can never drift apart),
with frozen v1 attack reference scores for BOTH players at every one
of the 225 flat cells (y*15+x), including occupied cells —
``scoring.score_attack`` scores every cell unconditionally, and the
v1 kernel must match it on all of them.

Usage (from the repo root):
``ml/.venv/bin/python ml/scripts/generate_kernel_v1_fixtures.py``
"""

from __future__ import annotations

import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

from gomoku_ml import game, scoring  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
V0_FIXTURES = os.path.join(REPO, "ml", "tests", "kernel_fixtures.json")
JSON_OUT = os.path.join(REPO, "ml", "tests", "kernel_v1_fixtures.json")


def _attack_scores(board: np.ndarray, player: int) -> list[int]:
    return [
        int(scoring.score_attack(board, m, player))
        for m in range(game.SIZE * game.SIZE)
    ]


def main() -> None:
    with open(V0_FIXTURES, encoding="utf-8") as f:
        v0 = json.load(f)["fixtures"]
    fixtures = []
    for fx in v0:
        board = np.array(fx["board"], dtype=np.int8).reshape(game.SIZE, game.SIZE)
        fixtures.append({
            "id": fx["id"],
            "source": fx["source"],
            "board": fx["board"],
            "to_move": fx["to_move"],
            "attack_black": _attack_scores(board, game.BLACK),
            "attack_white": _attack_scores(board, game.WHITE),
        })
    payload = {
        "_meta": {
            "description": "Fixed v1-kernel fixtures. attack_black / "
            "attack_white = scoring.score_attack for that colour at all "
            "225 flat cells (y*15+x), including occupied cells. Same 60 "
            "positions as kernel_fixtures.json. Generated by "
            "ml/scripts/generate_kernel_v1_fixtures.py.",
            "version": 1,
        },
        "fixtures": fixtures,
    }
    with open(JSON_OUT, "w", encoding="utf-8") as f:
        json.dump(payload, f, indent=1)
    print(f"wrote {JSON_OUT} ({len(fixtures)} fixtures)")


if __name__ == "__main__":
    main()
