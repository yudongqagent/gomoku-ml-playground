"""Generate fixed scoring-kernel fixtures with Python reference scores.

Writes two files (both generated — do not hand-edit):

* ``ml/tests/kernel_fixtures.json`` — test data for the NumPy kernel
  cross-check (``ml/tests/test_kernel_numpy.py``).
* ``src/kernel/fixtures.ts`` — the same positions for the web app: the
  WebGPU benchmark's self-check compares WGSL scores against the JS
  reference and the JS reference against these frozen Python scores.

Fixture set (60 positions, deterministic, seed 20261112):

* All 20 tactical positions from ``ml/gomoku_ml/tactical_positions.json``
  (open fours, blocks, gap fills, edge cases, VCF positions).
* Empty board, single centre stone, and a swap-rule opening (2 black +
  1 white, the auto-research program's opening).
* 37 random midgame boards from random playouts (8–80 plies, no game
  already won), seeded for reproducibility.

Reference scores are ``baseline.score_move`` for the side to move at
every one of the 225 flat cells (y*15+x), including occupied cells —
``score_move`` scores every cell unconditionally, and the kernels must
match it on all of them.

Usage (from the repo root): ``ml/.venv/bin/python ml/scripts/generate_kernel_fixtures.py``
"""

from __future__ import annotations

import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

from gomoku_ml import baseline, game  # noqa: E402

SEED = 20261112
N_RANDOM = 37
HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
TACTICAL_PATH = os.path.join(REPO, "ml", "gomoku_ml", "tactical_positions.json")
JSON_OUT = os.path.join(REPO, "ml", "tests", "kernel_fixtures.json")
TS_OUT = os.path.join(REPO, "src", "kernel", "fixtures.ts")


def _scores(board: np.ndarray, player: int) -> list[int]:
    return [int(baseline.score_move(board, m, player)) for m in range(game.SIZE * game.SIZE)]


def _fixture(fx_id: str, source: str, board: np.ndarray, to_move: int) -> dict:
    return {
        "id": fx_id,
        "source": source,
        "board": [int(v) for v in board.reshape(-1)],
        "to_move": int(to_move),
        "scores": _scores(board, to_move),
    }


def _board_from_stones(black: list, white: list) -> np.ndarray:
    board = game.empty_board()
    for x, y in black:
        board[y, x] = game.BLACK
    for x, y in white:
        board[y, x] = game.WHITE
    return board


def _random_midgame(rng: np.random.Generator, plies: int) -> np.ndarray:
    """Random playout of exactly ``plies`` moves; None if the game ends
    early (a won board is not a midgame position)."""
    board = game.empty_board()
    player = game.BLACK
    for _ in range(plies):
        legal = game.legal_moves(board)
        move = int(rng.choice(legal))
        board = game.apply_move(board, move, player)
        over, _ = game.game_over(board)
        if over:
            return None
        player = -player
    return board


def build_fixtures() -> list[dict]:
    fixtures: list[dict] = []

    with open(TACTICAL_PATH, encoding="utf-8") as f:
        tactical = json.load(f)["positions"]
    for pos in tactical:
        board = _board_from_stones(pos["black"], pos["white"])
        fixtures.append(_fixture(f"tactical-{pos['id']}", "tactical", board, pos["to_move"]))

    # Structured edge cases.
    fixtures.append(_fixture("empty-board", "structured", game.empty_board(), game.BLACK))
    centre = game.empty_board()
    centre[7, 7] = game.BLACK
    fixtures.append(_fixture("centre-stone", "structured", centre, game.WHITE))
    swap = game.empty_board()
    swap[7, 7] = game.BLACK
    swap[8, 8] = game.BLACK
    swap[6, 9] = game.WHITE
    fixtures.append(_fixture("swap-opening", "structured", swap, game.WHITE))

    # Random midgame boards, plies spread 8..80.
    rng = np.random.default_rng(SEED)
    plies_cycle = [8, 12, 16, 20, 24, 28, 32, 36, 40, 44, 48, 52, 56, 60, 64, 68, 72, 76, 80]
    made = 0
    attempts = 0
    while made < N_RANDOM and attempts < N_RANDOM * 20:
        attempts += 1
        plies = plies_cycle[made % len(plies_cycle)]
        board = _random_midgame(rng, plies)
        if board is None:
            continue
        to_move = game.BLACK if plies % 2 == 0 else game.WHITE
        fixtures.append(_fixture(f"random-{plies}ply-{made:02d}", "random", board, to_move))
        made += 1
    assert made == N_RANDOM, f"only generated {made}/{N_RANDOM} random boards"
    return fixtures


def _board_to_string(board: list[int]) -> str:
    return "".join(".BW"[v] if v in (0, 1, -1) else "?" for v in board)


def write_ts(fixtures: list[dict]) -> None:
    lines = [
        "// GENERATED by ml/scripts/generate_kernel_fixtures.py — do not hand-edit.",
        "// Same 60 positions as ml/tests/kernel_fixtures.json, with frozen Python",
        "// reference scores (baseline.score_move for the side to move, all 225",
        "// cells). The WebGPU benchmark self-check compares WGSL output against",
        "// the JS reference on these positions, and the JS reference against",
        "// these frozen scores.",
        "",
        "export interface KernelFixture {",
        "  id: string;",
        "  /** 225 chars, row-major (y*15+x): '.' empty, 'B' black, 'W' white. */",
        "  board: string;",
        "  toMove: 1 | -1;",
        "  /** Frozen Python reference scores, flat index y*15+x. */",
        "  scores: number[];",
        "}",
        "",
        "export const KERNEL_FIXTURES: KernelFixture[] = [",
    ]
    for fx in fixtures:
        board_str = _board_to_string(fx["board"])
        scores = ", ".join(str(s) for s in fx["scores"])
        lines.append(
            f"  {{ id: {json.dumps(fx['id'])}, board: {json.dumps(board_str)}, "
            f"toMove: {fx['to_move']}, scores: [{scores}] }},"
        )
    lines.append("];")
    lines.append("")
    with open(TS_OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def main() -> None:
    fixtures = build_fixtures()
    print(f"built {len(fixtures)} fixtures "
          f"({sum(1 for f in fixtures if f['source'] == 'tactical')} tactical, "
          f"{sum(1 for f in fixtures if f['source'] == 'structured')} structured, "
          f"{sum(1 for f in fixtures if f['source'] == 'random')} random)")
    payload = {
        "_meta": {
            "description": "Fixed scoring-kernel fixtures. scores = baseline.score_move "
            "for the side to move at all 225 flat cells (y*15+x), including "
            "occupied cells. Generated by ml/scripts/generate_kernel_fixtures.py "
            f"(seed {SEED}).",
            "version": 1,
        },
        "fixtures": fixtures,
    }
    with open(JSON_OUT, "w", encoding="utf-8") as f:
        json.dump(payload, f, indent=1)
    write_ts(fixtures)
    print(f"wrote {JSON_OUT}")
    print(f"wrote {TS_OUT}")


if __name__ == "__main__":
    main()
